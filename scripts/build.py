#!/usr/bin/env python3
"""Assemble the single self-contained index.html that GitHub Pages serves.

Zero dependencies (Python 3 standard library only). Sources:

    src/shell.html      page shell with __CSS__ / __SCRIPT__ /
                        __PIET_DATA_URI__ / __FAVICON_DATA_URI__ tokens
    src/style.css       the stylesheet, inlined into <style>
    src/quiz.js         game logic, inlined after the data pools
    src/data/*.json     question pools, injected as `var NAME = ...;`
    assets/piet-hello-world.webp   the Piet program image, inlined as a
                        data URI in the <img id="codeImg"> tag
    assets/favicon.svg  inlined as a data URI favicon

Usage:
    python3 scripts/build.py           rewrite index.html
    python3 scripts/build.py --check   exit 1 if index.html is stale
"""
import base64
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Pool variables in the exact order the original page declared them.
DATA_FILES = [
    ("src/data/normal.json", ["QUESTIONS", "DISTRACTORS", "SUBS"]),
    ("src/data/hard.json", ["HARD_FRAGMENTS", "REVERSE_PROMPT", "HARD_REVERSE", "HARD_WIDE"]),
    ("src/data/expert.json", ["EXPERT_ID", "EXPERT_ODD_PROMPT", "EXPERT_ODD",
                              "EXPERT_FAMILIES", "EXPERT_TWO", "EXPERT_PAIR"]),
]

DATA_HEADER = """\
// Question pools — generated by scripts/build.py from src/data/*.json.
// NORMAL MODE DATA — hint and note here are Normal-only and deliberately
// clear and specific. Hard Mode has its own separate pools below
// (HARD_FRAGMENTS / HARD_REVERSE / HARD_WIDE) with its own vaguer
// weakHint and Hard-only notes. Never copy a weakHint into this pool or
// a hint from this pool into Hard data: the two modes must not share
// hint/note wording.
"""


def data_js() -> str:
    parts = [DATA_HEADER]
    for rel, names in DATA_FILES:
        pools = json.loads((ROOT / rel).read_text(encoding="utf-8"))
        for name in names:
            if name not in pools:
                raise SystemExit(f"build: {name} missing from {rel}")
            dumped = json.dumps(pools[name], ensure_ascii=False, indent=2)
            if "</script" in dumped.lower() or "\u2028" in dumped or "\u2029" in dumped:
                raise SystemExit(f"build: {name} contains a sequence unsafe to inline")
            parts.append(f"var {name} = {dumped};")
    return "\n\n".join(parts)


def build() -> str:
    shell = (ROOT / "src/shell.html").read_text(encoding="utf-8")
    css = (ROOT / "src/style.css").read_text(encoding="utf-8").strip("\n")
    logic = (ROOT / "src/quiz.js").read_text(encoding="utf-8").strip("\n")
    script = data_js() + "\n\n" + logic
    piet_b64 = base64.b64encode((ROOT / "assets/piet-hello-world.webp").read_bytes()).decode()
    favicon_b64 = base64.b64encode((ROOT / "assets/favicon.svg").read_bytes()).decode()
    out = shell.replace("__CSS__", css)
    out = out.replace("__SCRIPT__", script)
    out = out.replace("__PIET_DATA_URI__", "data:image/webp;base64," + piet_b64)
    out = out.replace("__FAVICON_DATA_URI__", "data:image/svg+xml;base64," + favicon_b64)
    for token in ("__CSS__", "__SCRIPT__", "__PIET_DATA_URI__", "__FAVICON_DATA_URI__"):
        if token in out:
            raise SystemExit(f"build: token {token} was not replaced")
    return out


def main() -> int:
    target = ROOT / "index.html"
    built = build()
    if "--check" in sys.argv:
        if target.read_text(encoding="utf-8") != built:
            print("build: index.html is stale — run python3 scripts/build.py")
            return 1
        print("build: index.html is fresh")
        return 0
    target.write_text(built, encoding="utf-8")
    print(f"build: wrote index.html ({len(built.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
